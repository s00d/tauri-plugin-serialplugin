fn handler() -> BTreeSet<String> {
    HANDLER_COMMANDS.iter().map(|s| s.to_string()).collect()
}

fn read(rel: &str) -> String {
    std::fs::read_to_string(repo_root().join(rel)).unwrap_or_else(|e| panic!("{rel}: {e}"))
}

/// Given the handler's command list and `permissions/autogenerated/commands/`
/// When both are listed
/// Then every command has a permission file and every file a command
#[test]
fn every_command_has_a_permission_file() {
    let files: BTreeSet<String> =
        std::fs::read_dir(repo_root().join("permissions/autogenerated/commands"))
            .unwrap()
            .filter_map(|e| e.ok()?.file_name().into_string().ok())
            .filter_map(|n| n.strip_suffix(".toml").map(str::to_string))
            .collect();
    assert_eq!(handler(), files);
}

/// Given guest-js
/// When its `invoke('plugin:serialplugin|…')` calls are collected
/// Then they are exactly the handler's commands (`read` is kept for Rust callers)
#[test]
fn guest_js_invokes_exactly_the_handler_commands() {
    let js = read("guest-js/serial-port.ts");
    let needle = "plugin:serialplugin|";
    let mut used = BTreeSet::new();
    let mut rest = js.as_str();
    while let Some(i) = rest.find(needle) {
        let after = &rest[i + needle.len()..];
        let end = after
            .find(|c: char| !c.is_ascii_alphanumeric() && c != '_')
            .unwrap_or(after.len());
        used.insert(after[..end].to_string());
        rest = &after[end..];
    }
    let mut want = handler();
    want.remove("read");
    assert_eq!(used, want);
}

/// Given `permissions/default.toml`
/// When its `allow-*` entries are read
/// Then they grant every handler command (the harness's ACL is built from them)
#[test]
fn the_default_set_grants_every_command() {
    let granted: BTreeSet<String> = default_permission_commands().into_iter().collect();
    assert_eq!(granted, handler());
    assert!(!read("permissions/default.toml").contains("\"deny-open\""));
}

/// Given `open.toml`
/// When it is read
/// Then it defines `allow-open` (allowing open) and `deny-open` (denying it)
#[test]
fn open_has_allow_and_deny_permissions() {
    let open = read("permissions/autogenerated/commands/open.toml");
    for line in [
        "identifier = \"allow-open\"",
        "commands.allow = [\"open\"]",
        "identifier = \"deny-open\"",
        "commands.deny = [\"open\"]",
    ] {
        assert!(open.contains(line), "open.toml lacks {line}");
    }
}

/// Given the example app's capability
/// When its permissions are read
/// Then it grants `serialplugin:default` or `serialplugin:allow-open`
#[test]
fn the_example_app_may_open_ports() {
    let cap: Value = serde_json::from_str(&read(
        "examples/serialport-test/src-tauri/capabilities/default.json",
    ))
    .unwrap();
    let perms: Vec<&str> = cap["permissions"]
        .as_array()
        .unwrap()
        .iter()
        .filter_map(Value::as_str)
        .collect();
    assert!(perms
        .iter()
        .any(|p| *p == "serialplugin:default" || *p == "serialplugin:allow-open"));
}

/// Given an app whose ACL grants every command but `open`, and a live TCP bridge
/// When the webview calls `open` on the bridge
/// Then the call is refused and nothing connects; with `open` granted it connects
#[test]
fn the_acl_decides_whether_open_is_reachable() {
    let without: Vec<String> = default_permission_commands()
        .into_iter()
        .filter(|c| c != "open")
        .collect();
    let (listener, path) = tcp_listener();
    let denied = Plugin::with_commands(&without);
    assert!(open_ipc(&denied, &path).is_err());
    listener.set_nonblocking(true).unwrap();
    assert!(listener.accept().is_err(), "denied open connected");
    assert!(denied.managed().is_empty());

    let allowed = Plugin::new();
    assert_eq!(open_ipc(&allowed, &path), Ok(json!(path)));
    accept(&listener);
}
