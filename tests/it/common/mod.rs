/// Exchange timeout of commands that get an answer: it only bounds a failure.
pub const ANSWERED_MS: u64 = 10_000;

pub fn repo_file(rel: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join(rel)
}

// ---------------------------------------------------------------- ACL

/// The plugin's manifest, read from its permission files as tauri-build does.
pub fn manifest() -> Manifest {
    static FILES: OnceLock<Vec<PermissionFile>> = OnceLock::new();
    let files = FILES.get_or_init(|| {
        let mut paths = vec![repo_file("permissions/default.toml")];
        let commands = std::fs::read_dir(repo_file("permissions/autogenerated/commands")).unwrap();
        paths.extend(commands.map(|entry| entry.unwrap().path()));
        paths
            .iter()
            .map(|p| toml::from_str(&std::fs::read_to_string(p).unwrap()).unwrap())
            .collect()
    });
    Manifest::new(files.clone(), None)
}

/// The runtime ACL of an app whose capability lists `permissions`.
fn authority(permissions: &[&str]) -> tauri::ipc::RuntimeAuthority {
    let acl = BTreeMap::from([("serialplugin".to_owned(), manifest())]);
    let capability: Capability = serde_json::from_value(json!({
        "identifier": "test",
        "windows": ["main"],
        "permissions": permissions,
    }))
    .unwrap();
    let resolved = Resolved::resolve(
        &acl,
        BTreeMap::from([("test".to_owned(), capability)]),
        Target::current(),
    )
    .expect("the capability resolves against the plugin's permissions");
    tauri::runtime_authority!(acl, resolved)
}

/// The ACL refused the call (Tauri's answer, not the plugin's).
pub fn refused(result: &Result<Value, Value>) -> bool {
    matches!(result, Err(Value::String(e))
        if e.contains("not allowed") || e.contains("explicitly denied"))
}

/// The call reached the command, which could not read its arguments.
pub fn bad_args(result: &Result<Value, Value>) -> bool {
    matches!(result, Err(Value::String(e)) if e.starts_with("invalid args"))
}

/// What a failed command reports (guest-js gets the message text).
pub fn kind(result: Result<Value, Value>) -> ErrorKind {
    let error = result.expect_err("the command fails");
    ErrorKind::from_message(error.as_str().expect("an error is its message"))
}

// ---------------------------------------------------------------- plugin

type Message = (usize, Value);

/// The plugin in a mock app, reached from the webview window `main`.
pub struct Plugin {
    app: Option<tauri::App<MockRuntime>>,
    pub webview: WebviewWindow<MockRuntime>,
    /// Receivers of the JS channels, by callback id.
    channels: Arc<Mutex<HashMap<u32, Sender<Message>>>>,
}

impl Plugin {
    /// With `serialplugin:default`.
    pub fn new() -> Self {
        Self::build(&["serialplugin:default"], None).expect("plugin init")
    }

    pub fn with_permissions(permissions: &[&str]) -> Self {
        Self::build(permissions, None).expect("plugin init")
    }

    /// With `plugins."serialplugin-config"` set to `config` in tauri.conf.
    pub fn with_config(config: Value) -> Result<Self, String> {
        Self::build(&["serialplugin:default"], Some(config))
    }

    fn build(permissions: &[&str], config: Option<Value>) -> Result<Self, String> {
        let mut context = mock_context(noop_assets());
        *context.runtime_authority_mut() = authority(permissions);
        if let Some(config) = config {
            context
                .config_mut()
                .plugins
                .0
                .insert("serialplugin-config".into(), config);
        }
        let channels = Arc::new(Mutex::new(HashMap::<u32, Sender<Message>>::new()));
        let receivers = channels.clone();
        let app = mock_builder()
            .plugin(tauri_plugin_serialplugin::init())
            .channel_interceptor(move |_, id, index, body| {
                if let InvokeResponseBody::Json(json) = body {
                    if let Some(tx) = receivers.lock().unwrap().get(&id.0) {
                        let _ = tx.send((index, serde_json::from_str(json).unwrap()));
                    }
                }
                true
            })
            .build(context)
            .map_err(|e| e.to_string())?;
        let webview = WebviewWindowBuilder::new(&app, "main", Default::default())
            .build()
            .expect("webview");
        Ok(Self {
            app: Some(app),
            webview,
            channels,
        })
    }

    /// `invoke('plugin:serialplugin|<cmd>', args)` as guest-js sends it.
    pub fn invoke(&self, cmd: &str, args: Value) -> Result<Value, Value> {
        invoke(&self.webview, cmd, args)
    }

    pub fn ok(&self, cmd: &str, args: Value) -> Value {
        self.invoke(cmd, args)
            .unwrap_or_else(|e| panic!("{cmd}: {e}"))
    }

    /// The call on a thread of its own.
    pub fn start(&self, cmd: &'static str, args: Value) -> JoinHandle<Result<Value, Value>> {
        let webview = self.webview.clone();
        std::thread::spawn(move || invoke(&webview, cmd, args))
    }

    /// The managed state: for Rust callers, and for what no command shows.
    pub fn sp(&self) -> SerialPort<MockRuntime> {
        let state = self.webview.state::<SerialPort<MockRuntime>>();
        state.inner().clone()
    }

    pub fn managed(&self) -> Vec<String> {
        serde_json::from_value(self.ok("managed_ports", json!({}))).unwrap()
    }

    pub fn open(&self, path: &str) -> Result<Value, Value> {
        self.invoke(
            "open",
            json!({ "path": path, "baudRate": BAUD, "timeout": 200 }),
        )
    }

    /// Open `device` over IPC; the device side is connected afterwards.
    pub fn open_device(&self, device: &mut Device) {
        assert_eq!(self.open(&device.path), Ok(json!(device.path)));
        device.connected();
    }

    /// A new device of `kind`, open.
    pub fn device(&self, kind: Kind) -> Device {
        let mut device = Device::new(kind);
        self.open_device(&mut device);
        device
    }

    /// A JS `Channel`: its id, and what reaches it.
    pub fn channel(&self) -> Events {
        static NEXT: AtomicU32 = AtomicU32::new(1000);
        let id = NEXT.fetch_add(1, Ordering::Relaxed);
        let (tx, rx) = mpsc::channel();
        self.channels.lock().unwrap().insert(id, tx);
        Events { id, rx, got: 0 }
    }

    /// `watch` with a new channel; `extra` is merged into the arguments.
    pub fn try_watch(&self, path: &str, extra: Value) -> (Events, Result<Value, Value>) {
        let events = self.channel();
        let mut args = json!({ "path": path, "options": {}, "channel": events.arg() });
        args.as_object_mut()
            .unwrap()
            .extend(extra.as_object().unwrap().clone());
        let result = self.invoke("watch", args);
        (events, result)
    }

    pub fn watch(&self, path: &str, extra: Value) -> Events {
        let (events, result) = self.try_watch(path, extra);
        assert_eq!(result, Ok(json!(events.id)), "watch returns the channel id");
        events
    }

    pub fn unwatch(&self, events: &Events) {
        self.ok("unwatch", json!({ "channelId": events.id }));
    }

    /// Wait until the hub read everything the device sent and holds `idle` (not 0: that is
    /// also so before the bytes came) bytes nobody took. On a watched port: [`Self::fence`].
    pub fn settled(&self, path: &str, idle: usize) {
        let sp = self.sp();
        serialplugin_testing::eventually(&format!("{path} holds {idle} bytes"), || {
            hub_buffered(&sp, path) == idle
                && self.invoke("bytes_to_read", json!({ "path": path })) == Ok(json!(idle))
        });
    }

    /// A second stream on the watched `path`: it shows what the hub handed to the watch.
    pub fn fence(&self, path: &str) -> Fence {
        let count = Arc::new(AtomicUsize::new(0));
        let seen = count.clone();
        let sp = self.sp();
        let options = WatchOptions {
            serial_data_flush_interval_ms: Some(0),
            ..Default::default()
        };
        let sink = Arc::new(move |event| {
            if let CoreEvent::Event(SerialEvent::Data { data, .. }) = event {
                seen.fetch_add(data.len(), Ordering::SeqCst);
            }
            true
        });
        let id = sp.watch_core(path.into(), options, None, sink).unwrap();
        Fence { sp, id, count }
    }

    /// Run the app; the user closes its only window at once.
    pub fn exit(&mut self) {
        let window = self.webview.clone();
        self.app.take().unwrap().run_return(move |_, event| {
            if let tauri::RunEvent::Ready = event {
                window.destroy().unwrap();
            }
        });
    }
}

impl Drop for Plugin {
    /// Nothing of a (failed) case stays behind: the port-list watches are process-wide.
    fn drop(&mut self) {
        let sp = self.sp();
        let _ = sp.close_all();
        for id in self.channels.lock().unwrap().keys() {
            let _ = sp.unwatch_ports(*id);
        }
    }
}

fn invoke(webview: &WebviewWindow<MockRuntime>, cmd: &str, args: Value) -> Result<Value, Value> {
    let request = InvokeRequest {
        cmd: format!("plugin:serialplugin|{cmd}"),
        callback: CallbackFn(0),
        error: CallbackFn(1),
        url: if cfg!(windows) {
            "http://tauri.localhost"
        } else {
            "tauri://localhost"
        }
        .parse()
        .unwrap(),
        body: InvokeBody::Json(args),
        headers: Default::default(),
        invoke_key: INVOKE_KEY.to_string(),
    };
    get_ipc_response(webview, request).map(|b| b.deserialize::<Value>().expect("json response"))
}

/// See [`Plugin::fence`]; the stream ends with it.
pub struct Fence {
    sp: SerialPort<MockRuntime>,
    id: SubscriptionId,
    count: Arc<AtomicUsize>,
}

impl Fence {
    /// Wait until the hub has handed out `n` bytes since the fence stands.
    pub fn wait(&self, n: usize) {
        serialplugin_testing::eventually(&format!("the hub routed {n} bytes"), || {
            self.count.load(Ordering::SeqCst) >= n
        });
    }
}

impl Drop for Fence {
    fn drop(&mut self) {
        let _ = self.sp.unwatch_core(self.id);
    }
}

// ---------------------------------------------------------------- events

/// A watch event as the JS side reads it.
#[derive(Clone, Debug, PartialEq)]
pub enum Event {
    Data(Vec<u8>),
    Urc(String),
    Disconnect,
    Error(String),
}

impl Event {
    fn parse(v: &Value) -> Self {
        let text = |key: &str| v[key].as_str().unwrap_or_else(|| panic!("{v}")).to_string();
        match text("kind").as_str() {
            "data" => {
                let data: Vec<u8> = serde_json::from_value(v["data"].clone()).unwrap();
                assert_eq!(v["size"], data.len(), "{v}");
                Self::Data(data)
            }
            "urc" => Self::Urc(text("line")),
            "disconnect" => {
                text("reason");
                Self::Disconnect
            }
            "error" => Self::Error(text("message")),
            _ => panic!("{v}"),
        }
    }
}

/// The JS side of a channel.
pub struct Events {
    pub id: u32,
    rx: Receiver<Message>,
    /// Messages read so far: JS orders them by index, so none may be skipped.
    got: usize,
}

impl Events {
    pub fn arg(&self) -> String {
        format!("__CHANNEL__:{}", self.id)
    }

    fn take(&mut self, (index, value): Message) -> Value {
        assert_eq!(index, self.got, "channel {}: message order", self.id);
        self.got += 1;
        value
    }

    /// The next message, whatever it is.
    pub fn message(&mut self) -> Value {
        let message = self.rx.recv_timeout(WAIT).expect("a channel message");
        self.take(message)
    }

    /// The next message, or `None` when none came in time.
    pub fn message_within(&mut self, time: std::time::Duration) -> Option<Value> {
        let message = self.rx.recv_timeout(time).ok()?;
        Some(self.take(message))
    }

    pub fn try_message(&mut self) -> Option<Value> {
        let message = self.rx.try_recv().ok()?;
        Some(self.take(message))
    }

    /// The next event of a watch on `path`.
    pub fn next(&mut self, path: &str) -> Event {
        let v = self.message();
        assert_eq!(v["path"], path, "{v}");
        Event::parse(&v)
    }

    pub fn try_next(&mut self, path: &str) -> Option<Event> {
        let v = self.try_message()?;
        assert_eq!(v["path"], path, "{v}");
        Some(Event::parse(&v))
    }

    /// Data events until `done` holds for the bytes; any other event fails.
    pub fn data_until(&mut self, path: &str, done: impl Fn(&[u8]) -> bool) -> Vec<u8> {
        let mut got = Vec::new();
        while !done(&got) {
            match self.next(path) {
                Event::Data(data) => got.extend(data),
                other => panic!("{other:?} after {:?}", String::from_utf8_lossy(&got)),
            }
        }
        got
    }
}

// ---------------------------------------------------------------- devices

/// macOS refuses a baud rate on a PTY (`IOSSIOSPEED` is ENOTTY); 0 leaves it alone.
pub const PTY_KEEPS_BAUD: bool = cfg!(target_os = "macos");
/// Opens every device.
pub const BAUD: u32 = if PTY_KEEPS_BAUD { 0 } else { 115_200 };

#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Kind {
    #[cfg(unix)]
    Pty,
    Tcp,
}

pub const KINDS: &[Kind] = &[
    #[cfg(unix)]
    Kind::Pty,
    Kind::Tcp,
];

enum Side {
    #[cfg(unix)]
    Pty(serialport::TTYPort),
    Tcp(TcpListener, Option<TcpStream>),
}

/// The device side of a port; dropping it is unplugging.
pub struct Device {
    pub kind: Kind,
    pub path: String,
    side: Side,
}

impl Device {
    pub fn new(kind: Kind) -> Self {
        let (side, path) = match kind {
            #[cfg(unix)]
            Kind::Pty => {
                let peer::Pty { device, path, .. } = peer::pty();
                (Side::Pty(device), path)
            }
            Kind::Tcp => {
                let (listener, path) = peer::tcp_listener();
                (Side::Tcp(listener, None), path)
            }
        };
        Self { kind, path, side }
    }

    /// The host opened the port (again): a new TCP connection replaces the old one.
    pub fn connected(&mut self) {
        // Without PTYs (Windows) every device is a TCP bridge.
        #[allow(irrefutable_let_patterns)]
        if let Side::Tcp(listener, stream) = &mut self.side {
            *stream = Some(peer::accept(listener));
        }
    }

    pub fn io(&mut self) -> &mut dyn Io {
        match &mut self.side {
            #[cfg(unix)]
            Side::Pty(master) => master,
            Side::Tcp(_, stream) => stream.as_mut().expect("connected"),
        }
    }

    pub fn clone_io(&self) -> Box<dyn Io> {
        match &self.side {
            #[cfg(unix)]
            Side::Pty(master) => Box::new(master.try_clone_native().unwrap()),
            Side::Tcp(_, stream) => Box::new(stream.as_ref().unwrap().try_clone().unwrap()),
        }
    }

    pub fn send(&mut self, bytes: &[u8]) {
        self.io().write_all(bytes).unwrap();
    }

    pub fn recv_until(&mut self, done: impl Fn(&[u8]) -> bool) -> Vec<u8> {
        peer::recv_until(self.io(), done)
    }

    /// The next command line, CR included.
    pub fn command(&mut self) -> Vec<u8> {
        self.recv_until(|b| b.ends_with(b"\r"))
    }

    /// Let `modem` answer on this device.
    pub fn serve(&self, modem: serialplugin_testing::Modem) -> peer::Server {
        peer::serve(self.clone_io(), modem)
    }

    /// Answer the next command line with `reply`.
    pub fn answer(&self, reply: &'static [u8]) -> JoinHandle<Vec<u8>> {
        let mut io = self.clone_io();
        std::thread::spawn(move || {
            let command = peer::recv_until(io.as_mut(), |b| b.ends_with(b"\r"));
            io.write_all(reply).unwrap();
            command
        })
    }
}

// ---------------------------------------------------------------- what no command shows

/// Bytes the RX hub of `path` holds for a `read`; `bytes_to_read` adds what is still in the
/// driver. `usize::MAX` when the port is not connected.
fn hub_buffered(sp: &SerialPort<MockRuntime>, path: &str) -> usize {
    let ports = sp.serialports.lock().unwrap();
    match ports.get(path).map(|i| &i.state) {
        Some(PortState::Connected(cp)) => {
            let hub = cp.rx_hub.lock().unwrap();
            hub.as_ref().map_or(0, |h| h.shared().buffered_len())
        }
        _ => usize::MAX,
    }
}

/// The plugin's read handle of `path`.
pub fn with_port<T>(
    sp: &SerialPort<MockRuntime>,
    path: &str,
    f: impl FnOnce(&dyn serialport::SerialPort) -> T,
) -> T {
    let port = {
        let ports = sp.serialports.lock().unwrap();
        match ports.get(path).map(|i| &i.state) {
            Some(PortState::Connected(cp)) => cp.port.clone(),
            _ => panic!("{path} is not connected"),
        }
    };
    let port = port.lock().unwrap();
    f(port.as_ref())
}
